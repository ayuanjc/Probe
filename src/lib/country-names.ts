/** 码 → 中文名。查不到原样返回码（大小写归一），空值返回 undefined。 */
export function countryLabel(code: string | null | undefined): string | undefined {
  const raw = String(code ?? "").trim().toUpperCase();
  if (!raw) return undefined;
  return COUNTRY_NAMES[raw] ?? raw;
}
